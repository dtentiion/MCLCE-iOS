#!/usr/bin/env python3
"""Pull the network manager a host needs out of upstream.

Common/Network/GameNetworkManager.cpp is the game side of the network
code. Most of it is the client's: starting a client connection, joining,
invites, the progress screens. It doesn't build here, where there's no
client yet, so the functions a host uses go into
upstream/Minecraft.Client/iOS_GameNetworkManager.inc as they are, and
Game/MCLENetwork.cpp compiles them with the few it has of its own.

The Windows64 build's IQNet and IQNetPlayer are in Extrax64Stubs.cpp,
which isn't built here either. They go into iOS_QNet.inc.

Idempotent, rewrites both .inc files every run.
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CLIENT = REPO / "upstream" / "Minecraft.Client"
GNM = CLIENT / "Common" / "Network" / "GameNetworkManager.cpp"
X64 = CLIENT / "Extrax64Stubs.cpp"
OUT_GNM = CLIENT / "iOS_GameNetworkManager.inc"
OUT_QNET = CLIENT / "iOS_QNet.inc"

# CGameNetworkManager members taken whole
FUNCTIONS = [
    "CGameNetworkManager", "Terminate", "DoWork", "CorrectErrorIDS", "GetLocalPlayerMask",
    "GetPlayerCount", "GetOnlinePlayerCount", "AddLocalPlayerByUserIndex",
    "RemoveLocalPlayerByUserIndex", "GetLocalPlayerByUserIndex", "GetPlayerByIndex",
    "GetPlayerByXuid", "GetPlayerBySmallId", "GetHostPlayer", "RegisterPlayerChangedCallback",
    "UnRegisterPlayerChangedCallback", "HandleSignInChange", "ShouldMessageForFullSession",
    "IsInSession", "IsInGameplay", "IsReadyToPlayOrIdle", "IsLeavingGame", "SetLocalGame",
    "IsLocalGame", "SetPrivateGame", "IsPrivateGame", "IsHost", "IsInStatsEnabledSession",
    "SessionHasSpace", "GetSessionList", "GetGameSessionInfo", "SetSessionsUpdatedCallback",
    "GetFullFriendSessionInfo", "ForceFriendsSessionRefresh", "UpdateAndSetGameSessionData",
    "SendInviteGUI", "ResetLeavingGame",
    "IsNetworkThreadRunning", "SystemFlagSet", "SystemFlagGet", "CloseConnection",
    "GetPrimaryPad", "ServerReadyCreate", "ServerReady", "ServerReadyWait", "ServerReadyDestroy",
    "ServerReadyValid", "ServerStoppedCreate", "ServerStopped", "ServerStoppedDestroy",
    "ServerStoppedValid", "GetJoiningReadyPercentage", "FakeLocalPlayerJoined",
]


def body_end(src, start):
    """Index just past the brace that closes the one at src[start]."""
    depth = 0
    i = start
    n = len(src)
    while i < n:
        c = src[i]
        if c == '/' and src.startswith('//', i):
            i = src.index('\n', i)
            continue
        if c == '/' and src.startswith('/*', i):
            i = src.index('*/', i) + 2
            continue
        if c == '"' or c == "'":
            q = c
            i += 1
            while src[i] != q:
                i += 2 if src[i] == '\\' else 1
            i += 1
            continue
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    sys.exit("unbalanced braces")


def definition(src, name):
    """The text of CGameNetworkManager::name's definition, from the start of its line."""
    found = [m for m in re.finditer(r"^[^\n;{}#/]*\bCGameNetworkManager::" + re.escape(name) + r"\s*\(", src, re.M)]
    if len(found) != 1:
        sys.exit(f"CGameNetworkManager::{name}: found {len(found)} definitions")
    brace = src.index("{", found[0].end())
    if ";" in src[found[0].end():brace]:
        sys.exit(f"CGameNetworkManager::{name}: that is a declaration")
    return src[found[0].start():body_end(src, brace)]


for path in (GNM, X64):
    if not path.exists():
        sys.exit(f"missing: {path}")

src = GNM.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
parts = ["// Generated by scripts/gen-network-manager.py from\n"
         "// Common/Network/GameNetworkManager.cpp. Don't edit.\n"]
for name in FUNCTIONS:
    parts.append(definition(src, name) + "\n")
OUT_GNM.write_text("\n".join(parts), encoding="utf-8", newline="\n")
print(f"wrote: {OUT_GNM}")

src = X64.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
first = "BYTE IQNetPlayer::GetSmallId()"
last = "void IQNet::EndGame()"
if src.count(first) != 1 or src.count(last) != 1:
    sys.exit("the IQNet block's ends weren't found once each in Extrax64Stubs.cpp")
a = src.index(first)
b = body_end(src, src.index("{", src.index(last)))
OUT_QNET.write_text("// Generated by scripts/gen-network-manager.py from Extrax64Stubs.cpp.\n"
                    "// Don't edit.\n\n" + src[a:b] + "\n", encoding="utf-8", newline="\n")
print(f"wrote: {OUT_QNET}")
